  /**
   *  A Gauss-Legendre rule of an even count of points: its positive nodes and their weights.
   */
  struct Rule
  {
    std::span<const double> Nodes   = {}; /**< The positive nodes, rising. */
    std::span<const double> Weights = {}; /**< Their weights.              */
  };

  /**
   *  The rule of twice a count of points.
   *
   *  It integrates every polynomial of degree below four times the count exactly over -1 to 1, by
   *  the sum of each weight times the values at its node and at its node's negative.
   *
   *  @pre          The count is from 1 to Pairs.
   *  @param  pairs Half the count of points.
   *  @return       The rule.
   */
  constexpr auto Ruled(std::size_t pairs) -> Rule
  {
    const std::size_t first = pairs * (pairs - 1) / 2;
    return {.Nodes   = std::span{Nodes}.subspan(first, pairs),
            .Weights = std::span{Weights}.subspan(first, pairs)};
  }

    constexpr auto Infinity() -> double
    {
      return std::numeric_limits<double>::infinity();
    }

    /**
     *  A curve's length by Simpson's rule over its stretches: an evaluator that shares nothing with
     *  the library's quadrature.
     *
     *  @param  curve  The curve.
     *  @param  ranges The stretches its speed is smooth over.
     *  @return        The length.
     */
    auto Simpson(const Curve &curve, const std::vector<Range> &ranges) -> double
    {
      constexpr int Panels = 20'000;
      double        total  = 0.0;
      for (const Range range : ranges)
      {
        const double step = (range.End - range.Start) / Panels;
        double       sum  = 0.0;
        for (int index = 0; index <= Panels; ++index)
        {
          const double along = range.Start + (step * index);
          const double speed = Length(Derivative(curve, along));
          if (index == 0 || index == Panels)
          {
            sum += speed;
          }
          else
          {
            sum += (index % 2 == 1 ? 4.0 : 2.0) * speed;
          }
        }
        total += sum * step / 3.0;
      }
      return total;
    }

    /**
     *  A spline's stretches between distinct knots within its domain.
     *
     *  @param  spline The spline.
     *  @return        The stretches.
     */
    auto Spans(const Spline &spline) -> std::vector<Range>
    {
      std::vector<Range> spans;
      const auto         degree = static_cast<std::size_t>(spline.Degree);
      for (std::size_t index = degree; index < spline.Poles.size(); ++index)
      {
        if (spline.Knots[index] < spline.Knots[index + 1])
        {
          spans.push_back({.Start = spline.Knots[index], .End = spline.Knots[index + 1]});
        }
      }
      return spans;
    }

    /**
     *  A whole ellipse's length by the trapezoidal rule over a turn, which for a smooth periodic
     *  speed converges to the last bits.
     *
     *  @param  map The ellipse's map.
     *  @return     The length of one turn.
     */
    auto Perimeter(const Matrix &map) -> double
    {
      constexpr int Steps = 4096;
      double        sum   = 0.0;
      for (int index = 0; index < Steps; ++index)
      {
        const double angle  = 2.0 * std::numbers::pi * index / Steps;
        sum                += Length((map.X * -std::sin(angle)) + (map.Y * std::cos(angle)));
      }
      return sum * 2.0 * std::numbers::pi / Steps;
    }


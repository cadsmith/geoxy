    /**
     *  How many steps of a double a value is from a reference.
     *
     *  @param  value     The value.
     *  @param  reference The reference.
     *  @return           The distance in steps of the reference.
     */
    auto StepsOff(double value, double reference) -> double
    {
      const double step = std::nextafter(std::abs(reference), Infinity()) - std::abs(reference);
      return std::abs(value - reference) / step;
    }

    /**
     *  A double-double from a double.
     *
     *  @param  value The double.
     *  @return       It.
     */
    auto Two(double value) -> Twofold::Double
    {
      return Twofold::Lifted(value);
    }

    /**
     *  A cubic Bézier coordinate at a parameter, in double-double.
     *
     *  @param  controls The coordinate's control values.
     *  @param  along    The parameter.
     *  @return          Its value there.
     */
    auto Cubed(const std::array<double, 4> &controls, Twofold::Double along) -> Twofold::Double
    {
      const Twofold::Double       rest   = Twofold::Difference(Two(1.0), along);
      Twofold::Double             sum    = {};
      const std::array<double, 4> scales = {1.0, 3.0, 3.0, 1.0};
      for (std::size_t index = 0; index < 4; ++index)
      {
        const Twofold::Two scaled = Twofold::TwoProduct(controls.at(index), scales.at(index));
        Twofold::Double    term   = {.High = scaled.High, .Low = scaled.Low};
        for (std::size_t power = 0; power < index; ++power)
        {
          term = Twofold::Multiply(term, along);
        }
        for (std::size_t power = index; power < 3; ++power)
        {
          term = Twofold::Multiply(term, rest);
        }
        sum = Twofold::Add(sum, term);
      }
      return sum;
    }

    /**
     *  The length of a cubic Bézier curve along one line, exactly but for double-double rounding:
     *  the sum of the distances between its ends and the turning points between them, the roots of
     *  its derivative.
     *
     *  @param  controls The control values along the line.
     *  @return          The length.
     */
    auto Travel(const std::array<double, 4> &controls) -> double
    {
      std::array<Twofold::Double, 3> steps{};
      for (std::size_t index = 0; index < 3; ++index)
      {
        const Twofold::Two step = Twofold::TwoSum(controls.at(index + 1), -controls.at(index));
        steps.at(index)         = {.High = step.High, .Low = step.Low};
      }
      const Twofold::Double square = Twofold::Add(Twofold::Difference(steps[0], steps[1]),
                                                  Twofold::Difference(steps[2], steps[1]));
      const Twofold::Double linear =
          Twofold::Multiply(Two(2.0), Twofold::Difference(steps[1], steps[0]));
      std::vector<Twofold::Double> turns = {Two(0.0)};
      const auto                   keep  = [&turns](Twofold::Double root) -> void
      {
        if (root.High > 0.0 && root.High < 1.0)
        {
          turns.push_back(root);
        }
      };
      if (std::fpclassify(square.High) == FP_ZERO)
      {
        if (std::fpclassify(linear.High) != FP_ZERO)
        {
          keep(Twofold::Divide(Twofold::Negated(steps[0]), linear));
        }
      }
      else
      {
        const Twofold::Double discriminant =
            Twofold::Difference(Twofold::Multiply(linear, linear),
                                Twofold::Multiply(Two(4.0), Twofold::Multiply(square, steps[0])));
        if (discriminant.High >= 0.0)
        {
          Twofold::Double root = Twofold::Root(discriminant);
          if (linear.High < 0.0)
          {
            root = Twofold::Negated(root);
          }
          const Twofold::Double half = Twofold::Multiply(Two(-0.5), Twofold::Add(linear, root));
          keep(Twofold::Divide(half, square));
          if (std::fpclassify(half.High) != FP_ZERO)
          {
            keep(Twofold::Divide(steps[0], half));
          }
        }
      }
      turns.push_back(Two(1.0));
      std::ranges::sort(turns, [](Twofold::Double lhs, Twofold::Double rhs) -> bool
                        { return lhs.High < rhs.High; });
      Twofold::Double total = {};
      for (std::size_t index = 0; index + 1 < turns.size(); ++index)
      {
        const Twofold::Double run = Twofold::Difference(Cubed(controls, turns.at(index + 1)),
                                                        Cubed(controls, turns.at(index)));
        total = Twofold::Add(total, run.High < 0.0 ? Twofold::Negated(run) : run);
      }
      return total.High + total.Low;
    }

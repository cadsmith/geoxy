  /**
   *  A rated spline as a spline.
   *
   *  @param  rated The rated spline.
   *  @return       The spline.
   */
  inline auto Splined(const Rated &rated) -> Spline
  {
    Spline spline = {
        .Degree = rated.Degree, .Knots = rated.Knots, .Poles = {}, .Weights = rated.Weights};
    for (std::size_t index = 0; index + 1 < rated.Points.size(); index += 2)
    {
      spline.Poles.push_back({.X = rated.Points[index], .Y = rated.Points[index + 1]});
    }
    return spline;
  }
